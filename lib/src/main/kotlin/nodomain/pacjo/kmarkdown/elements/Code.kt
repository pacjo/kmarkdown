package nodomain.pacjo.kmarkdown.elements

import nodomain.pacjo.kmarkdown.config.MarkdownRendererConfig

sealed class Code(val content: String) : Element() {

    class Inline(content: String) : Code(content) {
        override fun render(config: MarkdownRendererConfig): String = "`$content`"
    }

    class Block(content: String, val language: Language? = null) : Code(content) {
        override fun render(config: MarkdownRendererConfig): String =
            "```${language?.codeString}\n$content\n```"
    }
}

